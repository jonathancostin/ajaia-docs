// Writes the demo data: three users and two shared documents.
// - migrations/0001_seed.sql, so a fresh database gets it from `migrations apply`
// - scripts/reset-demo.sql, which puts an existing database back to that state
// Run with `node scripts/make-seed.ts`. Both outputs are committed. Password
// salts are random, so the three hash lines change on every run.
import { writeFileSync } from "node:fs";
import { hashPassword } from "../worker/password.ts";

const PASSWORD = "ajaia-demo";
const now = Date.UTC(2026, 10, 13);

const users = [
  { id: "u_alice", email: "alice@example.com", name: "Alice Nguyen" },
  { id: "u_bob", email: "bob@example.com", name: "Bob Okafor" },
  { id: "u_carol", email: "carol@example.com", name: "Carol Diaz" },
];

const text = (value: string, ...marks: string[]) => ({
  type: "text",
  text: value,
  ...(marks.length ? { marks: marks.map((type) => ({ type })) } : {}),
});
const paragraph = (...content: object[]) => ({ type: "paragraph", content });
const heading = (level: number, value: string) => ({ type: "heading", attrs: { level }, content: [text(value)] });
const list = (type: "bulletList" | "orderedList", items: object[][]) => ({
  type,
  content: items.map((item) => ({ type: "listItem", content: [paragraph(...item)] })),
});

const welcome = {
  type: "doc",
  content: [
    heading(1, "Welcome to Ajaia Docs"),
    paragraph(
      text("This document belongs to Alice. Bob can "),
      text("edit", "bold"),
      text(" it and Carol can only "),
      text("view", "italic"),
      text(" it. Use Switch user at the top to see it as each of them."),
    ),
    heading(2, "Things to try"),
    list("orderedList", [
      [text("Format some text with the toolbar, then refresh the page. Changes save on their own.")],
      [text("Go back to the document list and import a "), text(".docx", "bold"), text(", "), text(".md", "bold"), text(" or "), text(".txt", "bold"), text(" file.")],
      [text("Press "), text("Share", "bold"), text(", add a person and pick Can edit or Can view.")],
      [text("Switch to Bob and change something. Switch back to Alice, open "), text("History", "bold"), text(", and restore the version from before his change.")],
      [text("Download the document as Markdown.")],
    ]),
    heading(2, "How sharing works"),
    list("bulletList", [
      [text("The owner decides who has access. Editors can change the text. Viewers can only read.")],
      [text("The server checks every request, so a hidden button is never the only protection.")],
      [text("If two people save at the same time, the second is asked whose version to keep. The other version stays in History.")],
    ]),
  ],
};

const notes = {
  type: "doc",
  content: [
    heading(1, "Launch checklist"),
    paragraph(text("Bob owns this one and shared it with Alice as an editor.")),
    list("bulletList", [[text("Pick a launch date")], [text("Draft the announcement")], [text("Ask Alice to review")]]),
  ],
};

const q = (value: string) => `'${value.replaceAll("'", "''")}'`;

const lines: string[] = ["-- Demo data. Generated by scripts/make-seed.ts. The password for every account is on the login page."];
for (const user of users) {
  const hash = await hashPassword(PASSWORD);
  lines.push(
    `INSERT INTO users (id, email, name, password_hash, created_at) VALUES (${q(user.id)}, ${q(user.email)}, ${q(user.name)}, ${q(hash)}, ${now});`,
  );
}
const doc = (id: string, owner: string, title: string, content: object) =>
  `INSERT INTO documents (id, owner_id, title, content, version, created_at, updated_at, updated_by) VALUES (${q(id)}, ${q(owner)}, ${q(title)}, ${q(JSON.stringify(content))}, 1, ${now}, ${now}, ${q(owner)});`;
const share = (documentId: string, userId: string, role: string) =>
  `INSERT INTO document_shares (document_id, user_id, role, created_at) VALUES (${q(documentId)}, ${q(userId)}, ${q(role)}, ${now});`;

const documentLines = [
  doc("d_welcome", "u_alice", "Welcome to Ajaia Docs", welcome),
  share("d_welcome", "u_bob", "editor"),
  share("d_welcome", "u_carol", "viewer"),
  doc("d_launch", "u_bob", "Launch checklist", notes),
  share("d_launch", "u_alice", "editor"),
];

writeFileSync(new URL("../migrations/0001_seed.sql", import.meta.url), [...lines, ...documentLines].join("\n") + "\n");
writeFileSync(
  new URL("./reset-demo.sql", import.meta.url),
  [
    "-- Puts the demo back to its seeded state: removes every document, share and version,",
    "-- then re-creates the seeded documents. Users are left alone. Generated by scripts/make-seed.ts.",
    "DELETE FROM document_versions;",
    "DELETE FROM document_shares;",
    "DELETE FROM documents;",
    ...documentLines,
  ].join("\n") + "\n",
);
console.log("wrote migrations/0001_seed.sql and scripts/reset-demo.sql");
